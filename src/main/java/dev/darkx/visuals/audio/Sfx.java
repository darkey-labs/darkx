package dev.darkx.visuals.audio;

/** Звуки клиента. Все синтезируются процедурно в {@link SoundSynth}. */
public enum Sfx {
	OPEN,         // открытие меню
	CLOSE,        // закрытие меню
	ON,           // функция включена
	OFF,          // функция выключена
	TAB,          // переключение вкладки / категории
	CLICK,        // обычная кнопка
	POPUP_OPEN,   // раскрылись настройки / выпадающий список
	POPUP_CLOSE,  // свернулись
	SELECT,       // выбор пункта, цвета, темы
	SLIDER,       // шаг ползунка
	TOAST,        // уведомление
	FRIEND        // друг появился в сети
}
